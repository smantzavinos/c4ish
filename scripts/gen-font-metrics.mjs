// Generates src/lib/text/metrics.ts: Noto Sans advance widths (1/1000 em) for the
// weights c4ish renders with. Source: @fontsource/noto-sans (OFL). Run: pnpm gen:metrics
import * as fontkit from 'fontkit';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('@fontsource/noto-sans/package.json')), 'files');
const subsets = ['latin', 'latin-ext', 'greek'];
const styles = { r: ['400', 'normal'], m: ['500', 'normal'], s: ['600', 'normal'], b: ['700', 'normal'], i: ['400', 'italic'] };

const ranges = [[0x20, 0x7e], [0xa0, 0x17f], [0x391, 0x3c9], [0x2010, 0x2027], [0x2190, 0x21ff], [0x2200, 0x22ff], [0x2300, 0x23ff], [0x25a0, 0x25ff], [0x2713, 0x2717]];
const codes = [];
for (const [a, b] of ranges) for (let c = a; c <= b; c++) codes.push(c);

const out = {};
for (const [key, [weight, style]] of Object.entries(styles)) {
	const fonts = subsets.map((s) => fontkit.openSync(join(dir, `noto-sans-${s}-${weight}-${style}.woff2`)));
	const table = {};
	for (const code of codes) {
		for (const f of fonts) {
			if (f.hasGlyphForCodePoint(code)) {
				const g = f.glyphForCodePoint(code);
				table[code] = Math.round((g.advanceWidth / f.unitsPerEm) * 1000);
				break;
			}
		}
	}
	out[key] = table;
}

// Compact encoding: per style, "code:width" runs as one string to keep the module small.
const enc = Object.fromEntries(
	Object.entries(out).map(([k, t]) => [k, Object.entries(t).map(([c, w]) => `${Number(c).toString(36)}:${w.toString(36)}`).join(',')])
);
const src = `// GENERATED by scripts/gen-font-metrics.mjs from @fontsource/noto-sans (SIL OFL 1.1). Do not edit.
// Advance widths in 1/1000 em, keyed by base-36 code point. r=400 m=500 s=600 b=700 i=400 italic.
export const NOTO_SANS_WIDTHS: Record<'r' | 'm' | 's' | 'b' | 'i', string> = ${JSON.stringify(enc, null, '\t')};
`;
writeFileSync(new URL('../src/lib/text/metrics.ts', import.meta.url), src);
console.log('glyphs per style:', Object.fromEntries(Object.entries(out).map(([k, t]) => [k, Object.keys(t).length])));
